"""The final alpha as the DAG qex builds for it (SignalGraph), written as Graphviz in the style of the reversal DAG.
Run from the repo root with run 3's qex (see figures/run3/README.md):

    ALPHA_LAB=/tmp/run3lab uv run --project /tmp/run3lab python figures/dag/final_dag.py
    dot -Tsvg figures/dag/final-dag.dot -o images/qex-final-graph.svg

The expression is the one the deck shows: run 3's final alpha.qex without its `* field('member')` mask (30 nodes;
32 as run). Every node is a distinct cache key, so a shared subexpression appears once with several parents; those
are outlined in green. A node a `let` names carries that name.
"""
import collections, os, re, subprocess, sys
from qex import qex, SignalGraph

expr = subprocess.check_output(["git", "-C", os.path.expanduser("~/dev/alpha_lab"), "show", "b89945f:alpha.qex"], text=True)
expr = re.sub(r"\s*\*\s*field\('member'\)", "", expr)
flat = " ".join(expr.split())
g = SignalGraph(); g.add_signal(qex(flat), name="alpha")
body, final = flat[len("let "):].rsplit(" in ", 1)
names = {}
for name in [m.group(1) for m in re.finditer(r"(?:^|, )(\w+)\s*=", body)]:   # each let name -> its node
    names[qex(f"let {body} in {name}")._cache_key()] = name
root = g.outputs["alpha"]
for k, sig in g.nodes.items():                     # ts_beta keeps its inputs as signal1/signal2, which SignalGraph does not walk
    if hasattr(sig, "signal1"):
        g.dependencies[k] = [sig.signal1._cache_key(), sig.signal2._cache_key()]

SNAKE = {"TsSum": "ts_sum", "TsStd": "ts_std", "TsBeta": "ts_beta", "Delay": "delay", "DecayLinear": "decay_linear",
         "GroupDemean": "group_demean", "Demean": "demean", "Returns": "returns", "Power": "power", "Where": "where",
         "Max": "max", "Min": "min"}
OPS = {"Add": "+", "Sub": "−", "Mul": "×", "Div": "/", "Greater": ">", "Less": "<", "Neg": "−(·)"}
def label(key):
    kind, args = key[0], [a for a in key[1:] if not isinstance(a, tuple)]
    if kind == "Constant": return f"{args[0]:g}"
    if kind in OPS: return OPS[kind]
    if kind == "Returns": return f"returns({args[0]})"
    nkids = len(g.dependencies[key])
    if kind.startswith("Ts"): args = args[:1]           # the window; the rolling min_periods is the engine's default, not in the code
    shown = ["·"] * nkids + [f"'{a}'" if isinstance(a, str) else f"{a:g}" if isinstance(a, float) else str(a) for a in args if a is not None]
    return f"{SNAKE.get(kind, kind.lower())}({', '.join(shown)})"
parents = collections.Counter(c for k in g.nodes for c in g.dependencies[k])
ids = {k: f"n{i}" for i, k in enumerate(g.nodes)}
out = ["// generated by figures/dag/final_dag.py", "digraph final {", "  rankdir=BT; bgcolor=\"transparent\"; pad=0.2; nodesep=0.3; ranksep=0.2;",
       '  node [shape=box, style="rounded,filled", fillcolor="#131927", color="#2a3344", fontcolor="#e8eaf0",',
       '        fontname="IBM Plex Mono, DejaVu Sans Mono, monospace", fontsize=17, margin="0.14,0.04", penwidth=1.2];',
       '  edge [color="#6b7280", arrowsize=0.7, penwidth=1.1];']
for k, i in ids.items():
    lab = label(k); attrs = []
    if k in names: lab = f"{names[k]}\\n{lab}"
    if not g.dependencies[k] and k[0] != "Constant": attrs.append("shape=ellipse")
    if k[0] == "Constant": attrs.append('fontcolor="#f5a97f"')
    if parents[k] > 1: attrs += ['color="#3ee87a"', "penwidth=1.6"]
    if k == root: lab = f"alpha\\n{lab}"; attrs += ['color="#3ee87a"', 'fontcolor="#3ee87a"']
    out.append(f'  {i} [label="{lab}"{", " + ", ".join(attrs) if attrs else ""}];')
for k in g.nodes:
    for c in g.dependencies[k]:
        out.append(f"  {ids[c]} -> {ids[k]};")
out.append("}")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "final-dag.dot"), "w").write("\n".join(out) + "\n")
print(len(g.nodes), "nodes;", sum(1 for k in parents if parents[k] > 1), "shared:", [names.get(k, label(k)) for k in parents if parents[k] > 1])
